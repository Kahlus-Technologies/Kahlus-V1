#!/usr/bin/env python3
"""Emit the paper's results tables as LaTeX, generated from the raw artifacts.

Written 2026-08-28. Both candidate framings for the BrainBodyFM submission (the
W/H law as spine, or the FM benchmark as spine) need the same two tables, so
they are generated here rather than typed. Typing them is how a wrong number
reaches a paper.

The model is emitted under a blind alias because the submission is double-blind
and "Kahlus" is a unique, public name. Change ALIAS if a different one is
chosen; nothing else needs editing.

Run:
    python3 scripts/emit_paper_tables.py            # to stdout
    python3 scripts/emit_paper_tables.py --out docs/paper/tables.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BENCH = ROOT / "docs/results/eeg_fm_benchmark_2026-08-24"

# Double-blind: never emit the project name into the PDF.
ALIAS = r"\textsc{ours}"

# Published model names are fine to print; they are not ours.
PRETTY = {
    "cbramod__full_ft": "CBraMod (full ft)",
    "cbramod__frozen": "CBraMod (frozen)",
    "labram_base__full_ft": "LaBraM-Base (full ft)",
    "labram_base__frozen": "LaBraM-Base (frozen)",
    "eegpt__full_ft": "EEGPT (full ft)",
    "eegpt__frozen": "EEGPT (frozen)",
    "biot_prest16__full_ft": "BIOT (full ft)",
    "biot_prest16__frozen": "BIOT (frozen)",
}


def fmt_p(p: float | None) -> str:
    if p is None:
        return "--"
    if p < 1e-4:
        return r"$<$0.0001"
    return f"{p:.4f}"


def results_table(ps: dict) -> str:
    rows = []
    for hz in ps["by_horizon"]:
        h = hz["horizon"]
        if not hz["claim_eligible"]:
            continue  # h=1 was dropped as leak-dominated; never print it as a win
        ref = hz["reference_test_mse_mean"]
        best = min(hz["comparisons"], key=lambda c: c["test_mse_mean"])
        delta = best["mean_delta"]
        lo, hi = best["ci95_low"], best["ci95_high"]
        if best["significant_after_holm"] and delta > 0:
            verdict = r"\textbf{ours}"
        elif best["statistical_tie"] or not best["significant_after_holm"]:
            verdict = "tie"
        else:
            verdict = "rival"
        rows.append(
            f"    {h} & {ref:.4f} & {PRETTY.get(best['entrant_id'], best['entrant_id'])} & "
            f"{best['test_mse_mean']:.4f} & ${delta:+.4f}$ & $[{lo:+.4f}, {hi:+.4f}]$ & "
            f"{fmt_p(best['holm_p'])} & {verdict} \\\\"
        )
    n = ps["by_horizon"][0]["n_subjects"]
    return (
        "% Generated by scripts/emit_paper_tables.py -- do not edit by hand.\n"
        "\\begin{table}[t]\n"
        "  \\centering\n"
        "  \\small\n"
        "  \\caption{Paired subject-level comparison against the strongest external\n"
        f"  entrant at each horizon. $\\Delta$ = rival $-$ ours per test subject, so\n"
        f"  positive favours ours. Percentile bootstrap over {n} held-out subjects\n"
        "  (resampling unit is the subject, not the window), Holm-corrected across\n"
        "  the family. $h{=}1$ is omitted: it was excluded as leak-dominated before\n"
        "  the test look.}\n"
        "  \\label{tab:paired}\n"
        "  \\begin{tabular}{rrlrrrrl}\n"
        "    \\toprule\n"
        "    $h$ & ours MSE & best rival & rival MSE & $\\Delta$ & 95\\% CI & Holm $p$ & winner \\\\\n"
        "    \\midrule\n"
        + "\n".join(rows) + "\n"
        "    \\bottomrule\n"
        "  \\end{tabular}\n"
        "\\end{table}\n"
    )


def gate_table(gate: dict) -> str:
    passed, failed = [], []
    for k, v in sorted(gate.items()):
        if not isinstance(v, bool):
            continue
        if k == "scientific_claim_allowed":
            continue
        (passed if v else failed).append(k.replace("_", r"\_"))
    n = max(len(passed), len(failed))
    passed += [""] * (n - len(passed))
    failed += [""] * (n - len(failed))
    rows = "\n".join(f"    \\texttt{{{p}}} & \\texttt{{{f}}} \\\\"
                     for p, f in zip(passed, failed))
    return (
        "% Generated by scripts/emit_paper_tables.py -- do not edit by hand.\n"
        "\\begin{table}[t]\n"
        "  \\centering\n"
        "  \\small\n"
        "  \\caption{Gate outcome. The protocol was preregistered; the gate reports\n"
        "  \\texttt{scientific\\_claim\\_allowed} $=$ \\textsc{false}, so the ranking is\n"
        "  reported as evidence about transfer under these adapters and not as a\n"
        "  claim of superiority.}\n"
        "  \\label{tab:gate}\n"
        "  \\begin{tabular}{ll}\n"
        "    \\toprule\n"
        "    passed & failed \\\\\n"
        "    \\midrule\n"
        + rows + "\n"
        "    \\bottomrule\n"
        "  \\end{tabular}\n"
        "\\end{table}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path)
    a = ap.parse_args()

    ps = json.loads((BENCH / "paired_statistics_kahlus_reference.json").read_text())
    gate = json.loads((BENCH / "eeg_fm_benchmark_gate.json").read_text())

    if gate.get("scientific_claim_allowed") is not False:
        print("REFUSING: the gate no longer blocks the claim; the paper's framing "
              "must be revisited before these tables are used.")
        return 1

    out = results_table(ps) + "\n" + gate_table(gate)

    # Never let the project name reach the PDF.
    for term in ("Kahlus", "kahlus", "NeuroTwin"):
        if term in out:
            print(f"REFUSING: '{term}' appears in generated LaTeX; "
                  "double-blind would be broken.")
            return 1

    if a.out:
        a.out.write_text(out)
        print(f"wrote {a.out}")
    else:
        print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
